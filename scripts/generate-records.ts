import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { createGenerator } from "ts-json-schema-generator";
import { generateLexicon } from "./lexicon.ts";

const root = resolve(import.meta.dirname, "..");
const pnpm = process.env.npm_execpath;
if (!pnpm) throw new Error("Run record generation with pnpm records.");
const pnpmIsJavaScript = /\.(?:c|m)?js$/.test(pnpm);
const pnpmExecutable = pnpmIsJavaScript ? process.execPath : pnpm;
const pnpmArguments = pnpmIsJavaScript ? [pnpm] : [];
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: pnpm records [--check]");
}
const check = args[0] === "--check";
const directory = await mkdtemp(join(root, ".pymalloy-records-"));
const outputs = [
  ["protocol.json", "packages/protocol/schema/protocol.json"],
  ["records.py", "packages/python/src/pymalloy/_protocol/records.py"],
  ["lexicon.py", "packages/python/src/pymalloy/_authoring/lexicon.py"],
] as const;
try {
  const schema = createGenerator({
    path: join(root, "packages/protocol/src/records.ts"),
    type: "Records",
    tsconfig: join(root, "packages/protocol/schema/tsconfig.json"),
    skipTypeCheck: true,
  }).createSchema("Records");
  await writeFile(join(directory, "protocol.json"), JSON.stringify(schema, null, 2) + "\n");
  await writeFile(join(directory, "lexicon.py"), generateLexicon());
  await writeFile(
    join(directory, "python-model-options.json"),
    JSON.stringify({
      "#all#": { base_class_kwargs: { frozen: true, forbid_unknown_fields: true } },
    }),
  );
  execFileSync(
    "uv",
    [
      "run",
      "--frozen",
      "python",
      "-m",
      "datamodel_code_generator",
      "--input",
      join(directory, "protocol.json"),
      "--output",
      join(directory, "records.py"),
      "--input-file-type",
      "jsonschema",
      "--output-model-type",
      "msgspec.Struct",
      "--snake-case-field",
      "--enum-field-as-literal",
      "all",
      "--disable-timestamp",
      "--use-schema-description",
      "--use-standard-collections",
      "--target-python-version",
      "3.12",
      "--use-generic-container-types",
      "--formatters",
      "ruff-check",
      "ruff-format",
      "--keyword-only",
      "--extra-template-data",
      join(directory, "python-model-options.json"),
    ],
    { cwd: root, stdio: "inherit" },
  );
  execFileSync(
    "uv",
    [
      "run",
      "--frozen",
      "python",
      "-c",
      `
import ast
import sys
from pathlib import Path
path = Path(sys.argv[1])
module = ast.parse(path.read_text(encoding="utf-8"))
class Records(ast.NodeTransformer):
    def visit_Subscript(self, node):
        self.generic_visit(node)
        if isinstance(node.value, ast.Name) and node.value.id == "Sequence":
            node.value.id = "tuple"
            node.slice = ast.Tuple(elts=[node.slice, ast.Constant(value=Ellipsis)], ctx=ast.Load())
        return node
    def visit_ClassDef(self, node):
        self.generic_visit(node)
        if not (node.name.endswith("Request") or node.name in {"InspectionPosition", "Input"}):
            for field in node.body:
                if isinstance(field, ast.AnnAssign):
                    annotation = ast.unparse(field.annotation)
                    if "UnsetType" in annotation:
                        field.annotation = ast.parse(annotation.replace(" | UnsetType", "") + ("" if "None" in annotation else " | None"), mode="eval").body
                        if isinstance(field.value, ast.Name) and field.value.id == "UNSET":
                            field.value = ast.Constant(value=None)
                        elif isinstance(field.value, ast.Call):
                            for keyword in field.value.keywords:
                                if keyword.arg == "default":
                                    keyword.value = ast.Constant(value=None)
        if node.name == "Diagnostic":
            node.body.extend(ast.parse("""
def __post_init__(self):
    force_setattr(self, "data", freeze(self.data))
""").body)
        if node.name == "ParseReport":
            node.body.extend(ast.parse("""
@property
def ok(self) -> bool:
    return not any(item.severity == 'error' for item in self.diagnostics)
""").body)
        return node
module = Records().visit(module)
module.body[0:0] = ast.parse("from msgspec.structs import force_setattr; from pymalloy._protocol.snapshot import freeze").body
ast.fix_missing_locations(module)
path.write_text("# Generated by scripts/generate-records.ts.\\n" + ast.unparse(module) + "\\n", encoding="utf-8", newline="\\n")
`,
      join(directory, "records.py"),
    ],
    { cwd: root, stdio: "inherit" },
  );
  execFileSync("uv", ["run", "--frozen", "ruff", "check", "--fix", join(directory, "records.py")], {
    cwd: root,
    stdio: "inherit",
  });
  execFileSync(
    pnpmExecutable,
    [...pnpmArguments, "exec", "vp", "fmt", join(directory, "protocol.json")],
    {
      cwd: root,
      stdio: "inherit",
    },
  );
  execFileSync(
    "uv",
    [
      "run",
      "--frozen",
      "ruff",
      "format",
      "--config",
      join(root, "pyproject.toml"),
      "--config",
      'format.line-ending = "lf"',
      join(directory, "records.py"),
      join(directory, "lexicon.py"),
    ],
    { cwd: root, stdio: "inherit" },
  );
  execFileSync(
    "uv",
    [
      "run",
      "--frozen",
      "python",
      "-c",
      `
import importlib.util
import sys
import msgspec
spec = importlib.util.spec_from_file_location("generated_protocol", sys.argv[1])
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)
msgspec.json.Decoder(module.Records)
`,
      join(directory, "records.py"),
    ],
    { cwd: root, stdio: "inherit" },
  );
  const changed: string[] = [];
  for (const [name, destination] of outputs) {
    const generated = await readFile(join(directory, name));
    const target = join(root, destination);
    if (!existsSync(target) || !generated.equals(await readFile(target))) changed.push(destination);
  }
  if (check) {
    if (changed.length)
      throw new Error(`Generated files are stale. Run pnpm records:\n${changed.join("\n")}`);
    console.log("Protocol schema, Python records and Malloy lexicon are current.");
  } else {
    for (const [name, destination] of outputs) {
      if (changed.includes(destination))
        await rename(join(directory, name), join(root, destination));
    }
    console.log(`Updated ${changed.length} generated files.`);
  }
} finally {
  await rm(directory, { recursive: true, force: true });
}
